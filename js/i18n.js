const LANGUAGE_NAMES = { en: 'English', hi: 'हिन्दी', es: 'Español' };

function getLanguage() {
  try {
    return localStorage.getItem('lang') || 'en';
  } catch (e) {
    return 'en';
  }
}

function setLanguage(lang) {
  try {
    localStorage.setItem('lang', lang);
  } catch (e) {
    /* localStorage unavailable */
  }
  applyTranslations();
  document.dispatchEvent(new CustomEvent('zen:languagechange'));
}

function t(key) {
  const lang = getLanguage();
  return (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) || TRANSLATIONS.en[key] || key;
}

function applyTranslations() {
  document.documentElement.lang = getLanguage();

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });

  const switcher = document.getElementById('lang-switcher');
  if (switcher) switcher.value = getLanguage();
}

function initLanguageSwitcher() {
  const switcher = document.getElementById('lang-switcher');
  if (!switcher) return;
  switcher.value = getLanguage();
  switcher.addEventListener('change', () => setLanguage(switcher.value));
}

document.addEventListener('DOMContentLoaded', () => {
  applyTranslations();
  initLanguageSwitcher();
});
